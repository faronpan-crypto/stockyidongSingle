# ============================================================
# 解析函数：提取名称和代码
# ============================================================

def parse_stock(s):
    """解析 '名称(代码)' -> (名称, 代码)"""
    import re
    m = re.match(r'(.+?)\((\d+)\)', s)
    if m:
        return m.group(1).strip(), m.group(2).strip()
    return s, ""

