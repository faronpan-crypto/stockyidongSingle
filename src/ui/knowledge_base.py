def get_grades_by_stage(stage: str) -> List[str]:
    """按学段获取年级列表"""
    return STAGES.get(stage, [])


def get_subjects(grade: str) -> List[str]:
    """获取某年级的学科列表"""
    for stage, grades in STAGES.items():
        if grade in grades:
            return SUBJECTS_BY_STAGE.get(stage, [])
    return ["语文", "数学", "英语"]


def get_topics(grade: str, subject: str) -> List[Dict]:
    """获取某年级某学科的知识点列表 (含子知识点)"""
    return KNOWLEDGE.get(grade, {}).get(subject, [])


def get_topic_names(grade: str, subject: str) -> List[str]:
    """获取知识点名称列表 (扁平)"""
    topics = get_topics(grade, subject)
    names = [t["name"] for t in topics]
    # 把所有子知识点也拉平
    for t in topics:
        for child in t.get("children", []):
            if child not in names:
                names.append(child)
    return names


def search_topic(keyword: str) -> List[Tuple[str, str, str]]:
    """搜索知识点 → [(年级, 学科, 知识点名), ...]"""
    results = []
    kw = keyword.lower()
    for grade, subjects in KNOWLEDGE.items():
        for subject, topics in subjects.items():
            for t in topics:
                if kw in t["name"].lower():
                    results.append((grade, subject, t["name"]))
                for child in t.get("children", []):
                    if kw in child.lower():
                        results.append((grade, subject, t["name"]))
    return results


def stats() -> Dict:
    """统计数据"""
    total_topics = 0
    total_children = 0
    by_stage = {"小学": 0, "初中": 0, "高中": 0}
    for grade, subjects in KNOWLEDGE.items():
        for subject, topics in subjects.items():
            for t in topics:
                total_topics += 1
                total_children += len(t.get("children", []))
                for stage, grades in STAGES.items():
                    if grade in grades:
                        by_stage[stage] += 1
    return {
        "total_grades": len(KNOWLEDGE),
        "total_topics": total_topics,
        "total_children": total_children,
        "by_stage": by_stage,
    }


if __name__ == "__main__":
    s = stats()
    print("📚 知识点库统计:")
    print(f"  年级数: {s['total_grades']}")
    print(f"  主知识点: {s['total_topics']}")
    print(f"  子知识点: {s['total_children']}")
    print(f"  按学段: {s['by_stage']}")
